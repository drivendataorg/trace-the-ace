#!/usr/bin/env python
r"""Stage 3: generate clean transcripts with a local LLM (noise is added later).

One-shot generation writes a tidy ~700-word lesson against ~3,600 real words / ~267 turns,
which a discriminator separates trivially. So the lesson is generated by continuation, asking
the model to go on until the transcript reaches a real word-count target; passes are batched
across all still-short sessions to keep vLLM throughput. Output: clean.jsonl
{session_id, exemplar_src, lines: [[role, text]]}; inject_noise.py adds noise and timestamps.

    python scripts/gen_synth/generate.py --model Qwen/Qwen3-30B-A3B-Instruct-2507 \
        --sessions outputs/synth/sessions.jsonl --out outputs/synth/clean.jsonl
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

MEAN_WORDS_PER_UTT = 13.6   # measured (real w_total/n_utt); sets the word target

SYSTEM = ("You write realistic verbatim transcripts of one-on-one online tutoring "
          "lessons for UK school students. You mimic real speech-to-text output, "
          "including how LONG and repetitive real lessons are.")

STYLE = """STYLE RULES (violating any makes the transcript unusable):
- Output ONLY dialogue lines, one per line: "Tutor: ..." or "Student: ...".
- NO stage directions, NO narration, NO markdown, NO blank lines, NO speaker
  names inside the text.
- Do NOT write "um"/"uh"/"erm" fillers (they are added later, at controlled rates);
  use "Okay so", "All right", "Right", "And then", "as well" as natural connectors;
  numbers as digits; UK spelling and money (£).
- Speech is WORDY and a bit rambling, like real people talking: complete spoken
  sentences with restarts and hedges ("that would be", "so what we have to do is"),
  never clipped note-taking style. Use the connectors real tutors use, often:
  "all right", "okay so", "shall we ...?", "... as well", "let's have a look",
  "over here", "this question".
- Student: typical turns 3-9 words in spoken phrasing ("Yeah, I think it's 24",
  not just "24"); MOSTLY answers — asks a question only about one turn in ten
  ("Miss, is it ...?", "Do I add these?"); when the tutor asks "why" or "how",
  answers with 15-35 words working through their reasoning step by step;
  sometimes reads a question or their working aloud.
- Tutor: {tutor_style}. Most turns 12-35 words in full sentences; several times
  per objective a FULL teaching turn of 40-80 words introducing or re-explaining
  a concept or working an example step by step. The tutor checks CONSTANTLY:
  about four in five tutor turns contain a question (the next step, a quick
  check, "are you happy with that?", "what do we do next?").
- Praise briefly and plainly like a real UK tutor, vary the wording, praise at
  the natural moments (a correct answer, good reasoning) and move on. Do not
  start turns with "Now" more than occasionally."""
# No named praise phrases in STYLE on purpose: the model overuses any phrase the prompt
# mentions (avoid-lists included); inject_noise matches per-phrase rates to the real ones.

PROMPT = """Write the transcript of a ~45-minute online 1-on-1 lesson. Real lessons
are LONG: many short back-and-forth exchanges, several worked examples per objective,
frequent checks for understanding. Do not rush to the end.

The lesson covers these learning objectives IN ORDER, with the student showing
EXACTLY the described level of evidence (do NOT make the outcome more obvious than
described — real lessons are ambiguous):
{objectives_block}

Start with the joining ritual real online lessons have: a tech check ("Hello?
Can you hear me?", "Hello hello", "I can see you now"), a possible glitch
("sorry, you cut out for a second"), then brief small talk with {student}, then
teach. Include natural lesson mechanics: reading questions from slides, "can you
see my screen?", drawing/typing pauses, about {tech} connection hiccups.
{exemplar_block}
{style}"""

EXEMPLAR = """
REGISTER EXAMPLE — an excerpt from a REAL lesson (different student, different
topic). Match its rhythm, turn lengths, wording habits and plain phrasing
exactly; do NOT copy its content or names:
{excerpt}
END OF EXAMPLE.
"""

CONT = """Continue this in-progress tutoring transcript — it is only partway through,
do not wrap it up yet unless told.

Student: {student}. Objectives being worked through (with required evidence level):
{objectives_block}

Transcript so far ends with:
{tail}

Continue naturally from there, in the SAME "Tutor: ..." / "Student: ..." format.
Do NOT re-greet, do NOT repeat any line above, do NOT summarise. Keep teaching with
more examples and back-and-forth.{nudge} {closing}

{style}"""

NUDGE = (" IMPORTANT: the turns so far are TOO SHORT — write fuller spoken turns "
         "(tutor mostly 15-35 words with full worked explanations, student answering "
         "in complete phrases), not one-liners.")


def obj_block(objs):
    return "\n".join(
        f"{i+1}. \"{o['learning_objective']}\" — student evidence: {o['evidence']}"
        for i, o in enumerate(objs))


BRACKET_RE = re.compile(r"\[[^\]]*\]")
UMUH_STRIP_RE = re.compile(r"\b[Uu]m\b,?\s*|\b[Uu]h\b,?\s*")


def make_exemplar(files, session_id, n_lines=22):
    """A contiguous mid-lesson slice of a real transcript, deterministic per session_id.

    Cleaned of what the generator must not write (bracket tokens, um/uh; inject_noise adds them
    back at measured rates). Returns (excerpt, source_session_id); the source id is recorded in
    clean.jsonl so decontaminate.py can remove verbatim copies, which the model makes despite the
    instruction (~2% of sessions, runs of up to ~95 words).
    """
    import csv as _csv
    import random as _random
    r = _random.Random(session_id)
    for _ in range(4):  # rare unusable file -> retry
        path = r.choice(files)
        lines = []
        with open(path, newline="", encoding="utf-8", errors="replace") as f:
            for row in _csv.DictReader(f):
                role = (row.get("role") or "").strip().lower()
                if role not in ("tutor", "student"):
                    continue
                txt = UMUH_STRIP_RE.sub("", BRACKET_RE.sub(" ", row.get("content") or ""))
                txt = " ".join(txt.split())
                if txt:
                    lines.append(f"{'Tutor' if role == 'tutor' else 'Student'}: {txt}")
        if len(lines) >= 2 * n_lines:
            start = r.randrange(len(lines) // 4, len(lines) // 2)
            return "\n".join(lines[start:start + n_lines]), Path(path).stem
    return "", None


def parse_lines(text):
    out = []
    for ln in text.splitlines():
        m = re.match(r"^\s*(Tutor|Student)\s*:\s*(.+)$", ln.strip(), re.I)
        if m and m.group(2).strip():
            out.append([m.group(1).lower(), m.group(2).strip()])
    return out


def word_count(lines):
    return sum(len(t.split()) for _, t in lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--sessions", default="outputs/synth500/sessions.jsonl")
    ap.add_argument("--out", default="outputs/synth500/clean.jsonl")
    ap.add_argument("--exemplar-dir", default=None,
                    help="real transcripts dir; when set, each first-pass prompt carries "
                         "a ~22-line excerpt of a random real lesson as a register example "
                         "(style rules alone under-deliver)")
    ap.add_argument("--max-model-len", type=int, default=16384)
    ap.add_argument("--gpu-mem-util", type=float, default=0.90)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--min-lines", type=int, default=80,
                    help="a session with fewer parsed lines after all passes = failed")
    ap.add_argument("--target-frac", type=float, default=0.80,
                    help="accept a session once it reaches this fraction of its "
                         "expected word count (n_utt_target * 13.6 words/utt)")
    ap.add_argument("--max-passes", type=int, default=6,
                    help="max continuation passes before giving up on the length target")
    ap.add_argument("--utt-cap-frac", type=float, default=1.15,
                    help="also accept once lines >= this fraction of n_utt_target "
                         "(continuation passes tend to add more turns rather than longer "
                         "ones)")
    ap.add_argument("--tokens-per-pass", type=int, default=3072)
    ap.add_argument("--tail-lines", type=int, default=24,
                    help="how many trailing lines to show the model when continuing")
    args = ap.parse_args()

    sessions = [json.loads(ln) for ln in open(args.sessions, encoding="utf-8")]
    out = Path(args.out).expanduser()
    done = set()
    if out.exists():  # resumable at the session level
        done = {json.loads(ln)["session_id"] for ln in open(out, encoding="utf-8")}
        print(f"[gen] resuming: {len(done)} sessions already generated")
    todo = [s for s in sessions if s["session_id"] not in done]
    if not todo:
        print("[gen] nothing to do")
        return

    exemplar_files = []
    if args.exemplar_dir:
        import glob
        exemplar_files = sorted(glob.glob(str(Path(args.exemplar_dir).expanduser()
                                              / "*.csv")))
        print(f"[gen] exemplar pool: {len(exemplar_files)} real transcripts")

    from transformers import AutoTokenizer
    from vllm import LLM, SamplingParams
    tok = AutoTokenizer.from_pretrained(args.model)
    llm = LLM(model=args.model, max_model_len=args.max_model_len,
              gpu_memory_utilization=args.gpu_mem_util)

    def encode(msgs):
        try:
            return tok.apply_chat_template(msgs, add_generation_prompt=True,
                                           tokenize=True, enable_thinking=False)
        except (TypeError, ValueError):
            return tok.apply_chat_template(msgs, add_generation_prompt=True, tokenize=True)

    def build(item, final):
        s, lines = item["s"], item["lines"]
        style = STYLE.format(tutor_style=s["tutor_style"])
        ob = obj_block(s["objectives"])
        if not lines:
            ex, src = (make_exemplar(exemplar_files, s["session_id"])
                       if exemplar_files else ("", None))
            item["exemplar_src"] = src
            user = PROMPT.format(objectives_block=ob, student=s["student"],
                                 tech=max(1, round(s["tech_noise"])), style=style,
                                 exemplar_block=EXEMPLAR.format(excerpt=ex) if ex else "")
        else:
            tail = "\n".join(f"{'Tutor' if r == 'tutor' else 'Student'}: {t}"
                             for r, t in lines[-args.tail_lines:])
            closing = ("This is the END of the lesson — bring it to a natural close "
                       "with brief plain praise and goodbye (vary the wording; not "
                       "every lesson ends with 'see you next time')." if final else
                       "There is still more lesson to go.")
            wpu = word_count(lines) / max(len(lines), 1)
            user = CONT.format(student=s["student"], objectives_block=ob, tail=tail,
                               nudge=NUDGE if wpu < 11.0 else "",
                               closing=closing, style=style)
        return encode([{"role": "system", "content": SYSTEM},
                       {"role": "user", "content": user}])

    def target_words(s):
        return int(args.target_frac * s["n_utt_target"] * MEAN_WORDS_PER_UTT)

    pending = [{"s": s, "lines": []} for s in todo]
    n_written = 0
    with open(out, "a", encoding="utf-8") as f:
        for p in range(args.max_passes):
            if not pending:
                break
            final = (p == args.max_passes - 1)
            sp = SamplingParams(temperature=0.9, top_p=0.95,
                                max_tokens=args.tokens_per_pass, seed=args.seed + p)
            outs = llm.generate([{"prompt_token_ids": build(it, final)} for it in pending],
                                sampling_params=sp)
            still = []
            for it, o in zip(pending, outs):
                for role, txt in parse_lines(o.outputs[0].text):
                    if it["lines"] and it["lines"][-1] == [role, txt]:
                        continue  # drop an echoed line
                    it["lines"].append([role, txt])
                utt_cap = int(args.utt_cap_frac * it["s"]["n_utt_target"])
                if (word_count(it["lines"]) >= target_words(it["s"])
                        or len(it["lines"]) >= utt_cap or final):
                    if len(it["lines"]) >= args.min_lines:
                        f.write(json.dumps({"session_id": it["s"]["session_id"],
                                            "exemplar_src": it.get("exemplar_src"),
                                            "lines": it["lines"]}) + "\n")
                        n_written += 1
                    # else: dropped as too-short failure
                else:
                    still.append(it)
            f.flush()
            reached = len(pending) - len(still)
            print(f"[gen] pass {p}: {reached} reached target/finalised, {len(still)} continue "
                  f"(median words so far {sorted(word_count(i['lines']) for i in still)[len(still)//2] if still else 0})")
            pending = still

    print(f"[gen] done: {n_written} sessions written -> {out}")


if __name__ == "__main__":
    main()
